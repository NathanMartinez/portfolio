import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import ts from 'typescript';
import { experimental_generateTypes } from 'wrangler';

const source = 'wrangler.jsonc';
const { config, error } = ts.parseConfigFileTextToJson(source, await readFile(source, 'utf8'));
if (error) throw new Error(ts.flattenDiagnosticMessageText(error.messageText, '\n'));

// Application bindings come from the deployment config, but the adapter's compiled
// entrypoint must never become a source dependency of the application's typecheck.
delete config.main;
config.assets.directory = resolve(config.assets.directory);
const directory = '.wrangler/types';
await mkdir(directory, { recursive: true });
const configPath = `${directory}/bindings.json`;
await writeFile(configPath, JSON.stringify(config));
const { env } = await experimental_generateTypes({
	config: configPath,
	path: `${directory}/worker-configuration.d.ts`,
	includeRuntime: false
});
if (!env) throw new Error('Wrangler did not generate environment types');

// Wrangler includes Worker asset-import declarations in `env`, even without
// runtime types. Vite owns application asset imports; these declarations would
// become invalid module augmentations inside our module-scoped bindings file.
const workerAssets = new Set(['*.txt', '*.html', '*.sql', '*.bin', '*.wasm', '*.wasm?module']);
const declarations = ts.createSourceFile('env.d.ts', env, ts.ScriptTarget.Latest, true);
if (declarations.parseDiagnostics.length) {
	throw new Error(
		`Invalid Wrangler declarations:\n${declarations.parseDiagnostics
			.map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n'))
			.join('\n')}`
	);
}
const bindings = declarations.statements
	.filter((statement) => {
		if (!ts.isModuleDeclaration(statement) || !ts.isStringLiteral(statement.name)) return true;
		if (!workerAssets.has(statement.name.text)) {
			throw new Error(`Review new Wrangler module declaration: ${statement.name.text}`);
		}
		return false;
	})
	.map((statement) => statement.getFullText(declarations))
	.join('');

// Keep Worker types scoped to this module; browser DOM globals belong to SvelteKit.
await writeFile(
	`${directory}/worker-configuration.d.ts`,
	`// Generated by npm run cf-typegen. Do not edit.\nimport type { Fetcher } from '@cloudflare/workers-types';\n${bindings}\nexport type { Env };\n`
);
